def analyze_key_pattern():
    """Analyze the pattern in known keys with detailed debugging output"""
    patterns = []
    print("=== Starting key pattern analysis ===")
    
    for i in range(1, len(KNOWN_KEYS)):
        print(f"\nAnalyzing index {i}...")
        
        if i + 1 in KNOWN_KEYS:
            current = KNOWN_KEYS[i]
            next_key = KNOWN_KEYS[i + 1]
            print(f"Found consecutive keys: {i} and {i+1}")
            print(f"Key {i}: {hex(current)}")
            print(f"Key {i+1}: {hex(next_key)}")
            
            xor_result = current ^ next_key
            print(f"XOR result: {hex(xor_result)}")
            
            current_bits = bin(current).count('1')
            next_bits = bin(next_key).count('1')
            bit_diff = next_bits - current_bits
            print(f"Bit count: Current={current_bits}, Next={next_bits}, Diff={bit_diff}")
            
            patterns.append({
                'index': i,
                'current': hex(current),
                'next': hex(next_key),
                'xor': hex(xor_result),
                'bit_diff': bit_diff,
                'current_bits': current_bits,
                'next_bits': next_bits
            })
            print(f"Stored pattern for index {i}: {patterns[-1]}")
        else:
            print(f"Skipping index {i} - no subsequent key found")
    
    print("\n=== Analysis complete ===")
    print(f"Total patterns found: {len(patterns)}")
    return patterns

