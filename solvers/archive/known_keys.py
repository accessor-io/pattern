# Adding function convert_significant_bits_to_ascii to convert significant key bits to ascii.
def convert_significant_bits_to_ascii(key: int) -> str:
    """Convert the significant bits of the key into an ASCII string.
    
    This function extracts the hex representation of the key without leading zeros,
    pads it with a zero if necessary to ensure even length, and then converts each pair
    of hex digits to its corresponding ASCII character if printable. Non-printable characters are replaced with '.'.
    
    Args:
        key (int): The integer key.
        
    Returns:
        str: The converted ASCII representation.
    """
    hex_str = hex(key)[2:].lstrip('0')
    if not hex_str:
         hex_str = "0"
    if len(hex_str) % 2 != 0:
         hex_str = "0" + hex_str
    key_bytes = bytes.fromhex(hex_str)
    ascii_str = ""
    for byte in key_bytes:
         if 32 <= byte < 127:
             ascii_str += chr(byte)
         else:
             ascii_str += "."
    return ascii_str