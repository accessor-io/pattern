class BitcoinTransactionAnalyzer:
    def __init__(self):
        # Lazy import to avoid circular dependency
        from difference_table import DIFFERENCE_PATTERNS
        self.diffs = DIFFERENCE_PATTERNS
        self.tx_cache = load_tx_cache()
        self.ecdsa = ECDSA()
        self.verified_solutions = {}

    def generate_candidate(self, index: int) -> int:
        """Generate candidate using cache, difference table, or fallback"""
        if index in self.tx_cache:
            return self.tx_cache[index]['bit_pattern']
        
        if index in self.diffs:
            prev = self.generate_candidate(index - 1)
            return (prev + self.diffs[index]) % ORDER
        
        return (1 << index) - 1  # Fallback to 2^n-1 pattern

    def verify_solution(self, index: int) -> bool:
        """Unified verification with multiple validation layers"""
        if index in self.verified_solutions:
            return self.verified_solutions[index]
        
        candidate = self.generate_candidate(index)
        expected = KNOWN_SOLUTIONS.get(index)
        
        # Validation checks
        valid = (
            candidate == expected and
            candidate.bit_length() == index and
            bin(candidate).count('1') == index.bit_count()
        )
        
        self.verified_solutions[index] = valid
        return valid

    def analyze_index(self, txid_hex: str, index: int):
        """Full analysis for a single index"""
        txid_int = int(txid_hex, 16)
        candidates = self.generate_candidate(index)
        
        print(f"\nIndex {index} Analysis:")
        print("=" * 40)
        
        for method, candidate in [('Multiplication', candidates[0]), 
                                ('XOR', candidates[1])]:
            print(f"\nMethod: {method}")
            print(f"Candidate: 0x{candidate:064x}")
            
            extractions = self.extract_bits(candidate, index)
            for name, value in extractions.items():
                print(f"{name}: 0x{value:x} (Bits: {value:0{index}b})")
            
            if index in KNOWN_SOLUTIONS:
                expected = KNOWN_SOLUTIONS[index]
                print(f"\nExpected: 0x{expected:x}")
                matches = [k for k,v in extractions.items() if v == expected]
                if matches:
                    print(f"MATCH FOUND WITH: {', '.join(matches)}")
                else:
                    print("No direct matches found")
        
        print("=" * 40 + "\n")

