def generate_missing_keys():
    """Generate the full sequence filling in missing keys"""
    sequence = {}
    
    # Start with the known keys
    for pos, key in KNOWN_KEYS.items():
        sequence[pos] = key
    
    # The missing positions we need to fill
    missing_positions = []
    for i in range(1, 161):  # 1-indexed, from 1 to 160
        if i not in sequence:
            missing_positions.append(i)
    
    print(f"Found {len(missing_positions)} missing keys to generate")
    
    # Determine chunks of missing keys to interpolate between known keys
    for missing_pos in missing_positions:
        # Find the closest lower known key
        prev_key_pos = None
        for i in range(missing_pos - 1, 0, -1):
            if i in sequence:
                prev_key_pos = i
                break
        
        # Find the closest higher known key
        next_key_pos = None
        for i in range(missing_pos + 1, 161):
            if i in sequence:
                next_key_pos = i
                break
        
        # If we have a previous known key, use it to predict the next key
        if prev_key_pos is not None:
            current_key = sequence[prev_key_pos]
            current_pos = prev_key_pos
            
            # Generate all keys from the previous key up to our target missing key
            while current_pos < missing_pos:
                next_key = predict_next_key(current_key, current_pos)
                current_pos += 1
                if current_pos not in sequence:  # Only add if not already known
                    sequence[current_pos] = next_key
                current_key = sequence[current_pos]
    
    # Format the complete sequence
    complete_sequence = []
    for i in range(1, 161):
        if i in sequence:
            complete_sequence.append((i, sequence[i], i in KNOWN_KEYS))
        else:
            # This should not happen if the algorithm works correctly
            complete_sequence.append((i, "FAILED_TO_GENERATE", False))
    
    return complete_sequence

